const {chromium}=require('C:/Users/jader/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright')
const assert=require('node:assert/strict')
const {prepare}=require('./verify-screen-pattern.cjs')
;(async()=>{
 const browser=await chromium.launch({executablePath:process.env.REALMED_BROWSER_EXECUTABLE||undefined})
 try{
  const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[]
  page.on('pageerror',e=>errors.push(e.message));await prepare(page)
  await page.goto((process.env.REALMED_UI_TEST_URL||'http://127.0.0.1:5186')+'/central-de-guias/tratamentos')
  const nav=page.getByRole('navigation',{name:'Filas da Central de Guias'})
  const info=nav.getByRole('button',{name:/^Informações:/})
  await info.first().waitFor();assert.equal(await info.count(),11)
  await page.waitForURL(u=>u.searchParams.get('queue')==='READY')
  const url=page.url(),selected=await nav.locator('button[aria-pressed="true"]').innerText()
  for(let i=0;i<await info.count();i++){
   const button=info.nth(i),description=await button.getAttribute('title'),label=(await button.getAttribute('aria-label')).replace('Informações: ','')
   await button.focus();assert.equal(await page.locator('.notification-card').count(),0,'Focus alone must not display help')
   await button.press('Enter')
   const toast=page.locator('.notification-info').filter({hasText:label+': '+description});await toast.waitFor()
   assert.equal(await toast.evaluate(e=>getComputedStyle(e).backgroundColor),'rgb(23, 92, 211)')
   assert.equal(await toast.locator('.notification-timer').evaluate(e=>getComputedStyle(e).animationDuration),'10s')
   assert.equal(page.url(),url);assert.equal(await nav.locator('button[aria-pressed="true"]').innerText(),selected)
   assert.equal(await page.locator('#treatment-queue-help').count(),0)
   await button.click();assert.equal(await page.locator('.notification-info').count(),1,'Deduplicate repeated help')
   await toast.getByRole('button',{name:/Fechar notificação/}).click();await toast.waitFor({state:'hidden'})
  }
  await info.nth(3).click()
  const help=page.locator('.notification-info');await help.waitFor();const began=Date.now()
  await page.evaluate(async()=>{const {notify}=await import('/src/composables/useNotifications.ts');notify('Aviso padrão de teste','success')})
  await page.waitForTimeout(5500)
  assert.equal(await help.isVisible(),true,'Help must stay beyond five seconds')
  assert.equal(await page.locator('.notification-success').count(),0,'Other notices still expire at five seconds')
  await help.waitFor({state:'hidden',timeout:5200});assert.ok(Date.now()-began<11200)
  await page.setViewportSize({width:390,height:844});await info.last().click();await help.waitFor();await page.waitForTimeout(250)
  assert.equal(page.url(),url);assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2))
  await page.screenshot({path:'.deployment/queue-help-mobile.png'})
  assert.deepEqual(errors,[])
  console.log('PASS eleven queue descriptions in blue notifications, title identifies source tab, no queue/filter change or inline banner, keyboard, deduplication, close, real 10-second expiry, default 5 seconds preserved and mobile layout.')
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
